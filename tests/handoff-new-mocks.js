async page => {
  const assert=(value,message)=>{if(!value)throw new Error(message)};
  const start = async () => {
    await page.locator('#first-text').fill('Учебное условие');
    await page.locator('.pixel-start').click();
    await page.locator('.capabilities-toggle').click();
    await page.locator('[data-prototype-open]').click();
  };
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  await start();
  const prompt=await page.locator('#prototype-prompt').inputValue();
  assert(prompt.includes('mocks/') && prompt.includes('new_mocks/') && prompt.includes('не изменяй'), 'В промпте отсутствуют правила сохранения моков');
  const packageDownload=page.waitForEvent('download');
  await page.locator('[data-download]').click();
  await packageDownload;
  await page.locator('[data-sent]').click();
  const malicious=await page.evaluate(()=>Array.from(fflate.zipSync({'../new_mocks/data.json':fflate.strToU8('{}')})));
  await page.locator('.prototype-drop input').setInputFiles({name:'unsafe.zip',mimeType:'application/zip',buffer:Buffer.from(malicious)});
  await page.locator('[data-receive]').click();
  await page.waitForFunction(()=>document.querySelector('.prototype-feedback')?.textContent.includes('небезопасный путь'));
  await page.locator('.prototype-drop input').setInputFiles({name:'broken.zip',mimeType:'application/zip',buffer:Buffer.from('not a zip')});
  await page.locator('[data-receive]').click();
  await page.waitForFunction(()=>document.querySelector('.prototype-feedback')?.textContent.includes('корректный архив'));
  const zipped=await page.evaluate(()=>Array.from(fflate.zipSync({'project/mocks/data.json':fflate.strToU8('{"value":1}'),'project/new_mocks/data.json':fflate.strToU8('{"value":2}')})));
  await page.locator('.prototype-drop input').setInputFiles({name:'result.zip',mimeType:'application/zip',buffer:Buffer.from(zipped)});
  await page.locator('[data-receive]').click();
  await page.locator('#mock-reason').waitFor({state:'visible'});
  assert((await page.locator('.prototype-dialog').innerText()).includes('new_mocks/'), 'Новые моки не обнаружены');
  await page.locator('[data-save-answers]').click();
  assert((await page.locator('.prototype-feedback').innerText()).includes('все три вопроса'), 'Пустые ответы приняты');
  await page.reload();
  await start();
  await page.locator('#mock-reason').waitFor({state:'visible'});
  await page.locator('#mock-reason').fill('Появилось поле адреса');
  await page.locator('#mock-strategy').fill('Старые сохранить, новые сначала сравнить');
  await page.locator('#mock-preserve').fill('Сохранить контракт и сценарий поиска');
  await page.locator('[data-save-answers]').click();
  await page.locator('[data-adaptation]').waitFor({state:'visible'});
  assert((await page.locator('.prototype-result').innerText()).includes('адаптация ещё не выполнялись'), 'Показан недостоверный результат адаптации');
  const requestDownload=page.waitForEvent('download');
  await page.locator('[data-adaptation]').click();
  const request=await requestDownload;
  assert(request.suggestedFilename()==='mock-adaptation-request.md', 'Запрос не скачан');
  const stream=await request.createReadStream();
  let content=''; for await(const chunk of stream) content+=chunk.toString('utf8');
  assert(content.includes('Появилось поле адреса') && content.includes('project/new_mocks/data.json'), 'Ответы или пути не переданы в запрос');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('makora.prototype-handoff.v1')));
  assert(saved.mockAnswers.reason==='Появилось поле адреса' && saved.inspection.originalMocksPresent, 'Ответы или информация об оригинальных моках потеряны');
  return {newMocksDetected:true, unsafePathRejected:true, answersRestored:true, adaptationNotClaimed:true};
}
